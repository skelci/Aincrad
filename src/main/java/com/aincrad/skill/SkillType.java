package com.aincrad.skill;

/**
 * Enumerates the three categories of skills in Aincrad.
 */
public enum SkillType {
    /** A sword skill that chains into combos. */
    SWORD_SKILL,
    /** An active skill with a cooldown and MP cost. */
    ACTIVE_SKILL,
    /** A passive skill providing a permanent modifier. */
    PASSIVE_SKILL
}
